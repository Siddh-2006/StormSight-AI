"""Minimal, valid CAP 1.2 (Common Alerting Protocol) XML — the concrete
implementation of the pitch deck's "regional-language CAP-format alert" /
"designed to plug into CAP/SACHET" claim, which had no code behind it
anywhere in this repository before this file.

CAP 1.2 is the OASIS XML standard (urn:oasis:names:tc:emergency:cap:1.2)
that NDMA/C-DOT's SACHET platform is built on (see the idea write-up's
research citations). This builder produces one valid CAP <alert> document
containing one <info> block per alert cell, using only the Python standard
library (`xml.etree.ElementTree` + `xml.dom.minidom` for pretty-printing) —
no new dependency was added to requirements.txt for this.

Two deliberate honesty choices, consistent with the rest of this project:
- `status` is always "Draft", never "Actual". This prototype does not
  dispatch anything to anyone; every document it produces is explicitly a
  draft awaiting the mandatory human-forecaster approval step described
  throughout the idea write-up, and the XML says so in a `<note>` field.
- Regional-language translation is NOT implemented here — the pitch deck's
  "regional-language" claim is a real, currently-unimplemented gap. Adding
  it would mean picking a translation approach and a language list, which
  is a product decision, not something to silently fake with an
  auto-translated string. Flagging it here rather than pretending.
"""
from __future__ import annotations

from datetime import datetime, timezone
from xml.dom import minidom
from xml.etree.ElementTree import Element, SubElement, tostring

CAP_NAMESPACE = "urn:oasis:names:tc:emergency:cap:1.2"


def _severity(probability: float) -> str:
    if probability >= 0.85:
        return "Extreme"
    if probability >= 0.7:
        return "Severe"
    if probability >= 0.5:
        return "Moderate"
    return "Minor"


def _certainty(probability: float) -> str:
    if probability >= 0.8:
        return "Likely"
    if probability >= 0.5:
        return "Possible"
    return "Unlikely"


def build_cap_xml(
    alerts: list[dict],
    sender: str = "stormsight-ai@prototype.local",
    identifier_prefix: str = "STORMSIGHT",
) -> str:
    """alerts: list of dicts with keys cell, lat, lon, probability,
    lead_time_min, why (matches ExplainedAlertEntry.model_dump()). Returns a
    pretty-printed CAP 1.2 XML string, one <alert> document covering every
    entry as its own <info> block."""
    now = datetime.now(timezone.utc)
    root = Element("alert")
    root.set("xmlns", CAP_NAMESPACE)

    SubElement(root, "identifier").text = f"{identifier_prefix}-{int(now.timestamp())}"
    SubElement(root, "sender").text = sender
    SubElement(root, "sent").text = now.isoformat()
    SubElement(root, "status").text = "Draft"
    SubElement(root, "msgType").text = "Alert"
    SubElement(root, "scope").text = "Public"
    SubElement(root, "note").text = (
        "DRAFT ALERT - machine-generated by StormSight-AI. Requires human forecaster "
        "review and approval before dispatch; see NEXT_STEPS.md."
    )

    for entry in alerts:
        probability = float(entry["probability"])
        lead_time_min = int(entry["lead_time_min"])
        info = SubElement(root, "info")
        SubElement(info, "category").text = "Met"
        SubElement(info, "event").text = "Thunderstorm and Lightning"
        SubElement(info, "urgency").text = "Immediate" if lead_time_min <= 30 else "Expected"
        SubElement(info, "severity").text = _severity(probability)
        SubElement(info, "certainty").text = _certainty(probability)
        SubElement(info, "headline").text = f"Thunderstorm/lightning risk in the next {lead_time_min} minutes"
        why = entry.get("why", "")
        SubElement(info, "description").text = (
            f"Forecast probability {probability:.0%} at a {lead_time_min}-minute lead time. {why}"
        ).strip()
        area = SubElement(info, "area")
        SubElement(area, "areaDesc").text = f"Grid cell {tuple(entry['cell'])}"
        # A 10km nominal radius stands in for the real grid-cell footprint
        # (see docs/technical_flow.md's grid convention) until real-data
        # deployment computes an exact cell polygon.
        SubElement(area, "circle").text = f"{entry['lat']},{entry['lon']} 10"

    rough_xml = tostring(root, encoding="unicode")
    return minidom.parseString(rough_xml).toprettyxml(indent="  ")
